// Vision Font — shared model test vectors (JS side).
//   node Tests/test-model.js           check Extension/Resources/model.js + scale.js against Tests/vectors.json
//   node Tests/test-model.js --write   regenerate vectors.json from the JS model (source of truth)
// Tests/ModelCheck/main.swift checks the Swift port against the same file.
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const RES = path.join(__dirname, '..', 'Extension', 'Resources');
const M = require(path.join(RES, 'model.js'));
const VS = require(path.join(RES, 'scale.js'));
const FILE = path.join(__dirname, 'vectors.json');

const eye = (sph = 0, cyl = 0, add = 0) => ({ sph, cyl, axis: 180, add });
// Example presbyope (made-up values) used for the README table and tests.
const MYRX = wearing => ({ od: { sph: 0.5, cyl: -0.5, axis: 90, add: 2 }, os: { sph: 0.75, cyl: 0, axis: null, add: 2 }, age: 60, lens: 'progressive', wearing, pdFar: 64, pdNear: 61 });
const PROFILES = [
  ['default', VS.defaultRx()],
  ['example-no-glasses', MYRX(false)],
  ['example-progressives-on', MYRX(true)],
  ['example-lens-none-toggle-on', { ...MYRX(true), lens: 'none' }],
  ['example-single-vision-on', { ...MYRX(true), lens: 'single' }],
  ['emmetrope-30', { od: eye(), os: eye(), age: 30, lens: 'single', wearing: false }],
  ['myope-2-30', { od: eye(-2), os: eye(-2), age: 30, lens: 'single', wearing: false }],
  ['presbyope-55-add2', { od: eye(0, 0, 2), os: eye(0, 0, 2), age: 55, lens: 'single', wearing: false }],
  ['hyperope-1.5-45', { od: eye(1.5), os: eye(1.5), age: 45, lens: 'single', wearing: false }],
];
const DISTS = [30, 50, 70, 100];
const OPTS = [
  { name: 'css96', pxPerMm: null, comfort: 1, cap: 2.5 },
  { name: 'macbook-4.87ppm', pxPerMm: 4.87, comfort: 1, cap: 2.5 },
  { name: 'macbook-comfort80-cap4', pxPerMm: 4.87, comfort: 0.8, cap: 4 },
];
// (The web-app README table used a personal Rx and is no longer checked here.)
const README_TABLE = {};

function build() {
  const cases = [];
  for (const [profile, rx] of PROFILES) for (const o of OPTS) for (const d of DISTS) {
    const r = VS.pageScale(rx, d, { pxPerMm: o.pxPerMm, comfort: o.comfort, cap: o.cap });
    cases.push({ profile, opts: o.name, distanceCm: d, px: r.px, enlarge: r.enlarge, blur: r.blur, blurOD: r.blurOD, blurOS: r.blurOS,
      accommodation: r.accommodation, base: r.base, rawScale: r.rawScale, scale: r.scale });
  }
  return {
    note: 'Generated by node Tests/test-model.js --write from Extension/Resources/model.js + scale.js. Swift must match within 1e-9.',
    tolerance: 1e-9,
    profiles: Object.fromEntries(PROFILES),
    opts: Object.fromEntries(OPTS.map(o => [o.name, o])),
    cases,
  };
}

const fresh = build();
if (process.argv.includes('--write')) { fs.writeFileSync(FILE, JSON.stringify(fresh, null, 1) + '\n'); console.log(`wrote ${fresh.cases.length} cases to ${FILE}`); }
const stored = JSON.parse(fs.readFileSync(FILE, 'utf8'));

// 1. model.js in the extension is byte-identical to the web app's
const webModel = path.join(__dirname, '..', '..', 'vision-font-app', 'model.js');
if (fs.existsSync(webModel)) {
  assert.strictEqual(fs.readFileSync(webModel, 'utf8'), fs.readFileSync(path.join(RES, 'model.js'), 'utf8'), 'extension model.js differs from the web app model.js');
  console.log('✓ Extension/Resources/model.js is byte-identical to vision-font-app/model.js');
}

// 2. JS reproduces the stored vectors
assert.strictEqual(stored.cases.length, fresh.cases.length, 'vector count');
let maxErr = 0;
stored.cases.forEach((s, i) => {
  const f = fresh.cases[i];
  for (const k of ['px', 'enlarge', 'blur', 'blurOD', 'blurOS', 'accommodation', 'base', 'rawScale', 'scale']) {
    const e = Math.abs(s[k] - f[k]); maxErr = Math.max(maxErr, e);
    assert(e <= stored.tolerance, `${s.profile}/${s.opts}@${s.distanceCm} ${k}: ${f[k]} vs stored ${s[k]}`);
  }
});
console.log(`✓ ${stored.cases.length} vectors reproduced by the JS model (max |Δ| ${maxErr.toExponential(1)})`);

// 3. matches the web app README check table (rounded)
for (const [profile, rows] of Object.entries(README_TABLE)) rows.forEach(([px, enl, blur], i) => {
  const c = fresh.cases.find(x => x.profile === profile && x.opts === 'css96' && x.distanceCm === DISTS[i]);
  assert.strictEqual(c.px.toFixed(1), px.toFixed(1), `${profile} ${DISTS[i]} cm px`);
  assert.strictEqual(c.enlarge.toFixed(2), enl.toFixed(2), `${profile} ${DISTS[i]} cm enlarge`);
  if (blur > 0) assert.strictEqual(c.blur.toFixed(2), blur.toFixed(2), `${profile} ${DISTS[i]} cm blur`);
});

// 4. behaviour checks for the page scale
const get = (p, o, d) => fresh.cases.find(x => x.profile === p && x.opts === o && x.distanceCm === d);
assert(fresh.cases.every(c => c.scale >= 1 && c.scale <= VS.S.MAX_CAP), 'scale within [1, 4]');
assert(fresh.cases.filter(c => c.opts !== 'macbook-comfort80-cap4').every(c => c.scale <= 2.5 + 1e-12), 'default cap 2.5');
assert.strictEqual(get('example-no-glasses', 'macbook-4.87ppm', 50).scale, 2.5, 'no glasses at 50 cm hits the 2.5x cap');
assert(get('example-progressives-on', 'macbook-4.87ppm', 30).scale < get('example-no-glasses', 'macbook-4.87ppm', 30).scale, 'glasses on needs less scaling up close');
assert.deepStrictEqual(DISTS.map(d => get('example-lens-none-toggle-on', 'css96', d).px), DISTS.map(d => get('example-no-glasses', 'css96', d).px), 'lens "none" behaves as no glasses');
assert(VS.passesDeadband(1.0, 1.06) && !VS.passesDeadband(1.0, 1.04), '5% dead-band');
console.log('✓ page-scale behaviour (cap, clamp >= 1, lens none, 5% dead-band)');

console.log('\nPage scale, MacBook screen (4.87 CSS px/mm), comfort 100%, cap 2.5x:');
for (const p of ['example-no-glasses', 'example-progressives-on', 'emmetrope-30']) {
  console.log('  ' + p.padEnd(24) + DISTS.map(d => { const c = get(p, 'macbook-4.87ppm', d); return `${d}cm ${c.scale.toFixed(2)}x (${c.blur.toFixed(2)}D)`; }).join('   '));
}
console.log('\nAll JS model checks passed.');
